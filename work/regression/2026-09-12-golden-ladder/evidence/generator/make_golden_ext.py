#!/usr/bin/env python3
"""Generate the golden ladder's `ext/` corpus — deterministic, prefix-stable.

W-136 phase 2. The sealed golden benchmark's seed documents live in the fux
repo at `work/golden/seed/`; this script produces everything *around* them, so
a rung of N documents is 20 seed documents plus the first N-20 documents of the
stream this file emits.

## The one property that matters: PREFIX STABILITY

The ladder is **nested** — rung 200's documents are rung 100's documents, byte
for byte, plus 100 more. That is what makes two rungs comparable at all. So
document `i` of the stream must be byte-identical whatever `--count` is asked
for, which is why every document draws from `random.Random(SEED + i)` and never
from one shared stream. Nothing here may depend on `n`.

## The block, and why it is ten

Documents are emitted in blocks of ten, and each block holds the category mix
`work/golden/README.md` asks for exactly:

    0 sibling   1 adjacent  2 filler   3 sibling   4 adjacent
    5 variant   6 sibling   7 adjacent 8 filler    9 sibling

    -> sibling 4 (40%) · adjacent 3 (30%) · filler 2 (20%) · variant 1 (10%)

Every rung's ext count is a multiple of ten (80 · 180 · 480 · 980), so every
rung gets that mix and no rung ever cuts a block in half.

**Slot 5 and slot 6 are a supersession pair.** Slot 5 is the retired document
and is written under `ext/archive/`; slot 6 is its successor and declares
`supersedes:` pointing at it. They are adjacent in the stream so that a rung
boundary can never admit a `supersedes:` line whose target is not in the rung.

## The rule this file is most able to break

🔴 **No generated document may state a fact about a seed entity.** Vocabulary
may overlap — that is the point of a hard negative — but no named company,
person, facility, vendor, room, truck, form or incident from `seed/` may
appear. `SEED_ENTITIES` is the blacklist and `check_corpus()` enforces it over
the emitted bytes; the generator fails rather than writes a corpus that would
silently change the answer key's truth.

## Authored documents come first

`golden-ext-authored/` holds hand-written hard negatives, emitted in filename
order before anything generated, so the hardest documents are in *every* rung.
Each document's `origin` (`authored` | `generated`) is recorded per line in the
rung manifest.

Usage:
    python3 make_golden_ext.py --out <rung-dir> --count 980
    python3 make_golden_ext.py --check          # blacklist + determinism self-test
"""

