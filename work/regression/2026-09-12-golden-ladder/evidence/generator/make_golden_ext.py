def document(i: int) -> dict:
    """Document `i` of the ext stream. Depends on `i` alone."""
    r = rng_for(i)
    slot = i % 10
    cat = BLOCK[slot]

    if cat == "sibling":
        kind = SIBLING_KINDS[(i * 5 + slot) % len(SIBLING_KINDS)]
        key, ext, title = kind
        # slot 6 is the successor of the variant emitted at slot 5
        supersedes = None
        if slot == 6:
            vkind = SUPERSEDABLE[((i - 1) * 5 + 5) % len(SUPERSEDABLE)]
            supersedes = f"ext/archive/{i-1:05d}-{vkind[0]}-retired.md"
            kind = vkind
            key, ext, title = kind
        body = sibling_doc(i, r, kind, supersedes)
        path = f"ext/sibling/{i:05d}-{key}.{ext}"
        date = a_date(r, 2023, 2026)
    elif cat == "adjacent":
        kind = ADJACENT_KINDS[(i * 3 + slot) % len(ADJACENT_KINDS)]
        body = adjacent_doc(i, r, kind)
        path = f"ext/adjacent/{i:05d}-{kind[0]}.{kind[1]}"
        date = a_date(r, 2022, 2026)
    elif cat == "filler":
        kind = FILLER_KINDS[(i * 7 + slot) % len(FILLER_KINDS)]
        body = filler_doc(i, r, kind)
        path = f"ext/filler/{i:05d}-{kind[0]}.{kind[1]}"
        date = a_date(r, 2021, 2026)
    else:  # variant — retired half of the pair, archived
        kind = SUPERSEDABLE[(i * 5 + 5) % len(SUPERSEDABLE)]
        body = variant_doc(i, r, kind, kind[2])
        path = f"ext/archive/{i:05d}-{kind[0]}-retired.md"
        date = a_date(r, 2019, 2022)

    return {"path": path, "category": cat, "origin": "generated",
            "date": date, "text": body}


def authored() -> list[dict]:
    """Hand-written hard negatives, in filename order, ahead of the stream.

    Each carries a `# golden-ext: <category> <date>` first line (stripped
    before writing) so the manifest can record what it is without a side file.
    """
    out = []
    if not AUTHORED_DIR.is_dir():
        return out
    for p in sorted(AUTHORED_DIR.iterdir()):
        if p.name.startswith(".") or p.is_dir():
            continue
        raw = p.read_text(encoding="utf-8")
        first, _, rest = raw.partition("\n")
        m = re.match(r".*golden-ext:\s*(\w+)\s+(\S+)\s+(\S+?)(?:\s*-->)?\s*$", first)
        if not m:
            raise SystemExit(f"authored doc missing header: {p}")
        cat, date, dest = m.group(1), m.group(2), m.group(3)
        out.append({"path": dest, "category": cat, "origin": "authored",
                    "date": date, "text": rest})
    return out


def stream(n: int) -> list[dict]:
    """The first `n` ext documents: authored ones first, then generated."""
    docs = authored()
    if len(docs) > n:
        return docs[:n]
    i = 0
    while len(docs) < n:
        docs.append(document(i))
        i += 1
    return docs


