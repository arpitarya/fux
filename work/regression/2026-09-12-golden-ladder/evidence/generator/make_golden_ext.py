    if a.check:
        docs = stream(1000)
        bad = check_corpus(docs)
        if bad:
            print(f"FAIL: {len(bad)} seed-entity leaks")
            for b in bad[:40]:
                print("  " + b)
            return 1
        # prefix stability: the first 80 must be identical when asking for 980
        small = stream(80)
        big = stream(980)[:80]
        assert [d["path"] for d in small] == [d["path"] for d in big], "path drift"
        assert [d["text"] for d in small] == [d["text"] for d in big], "byte drift"
        # category mix at every rung boundary
        for n in (80, 180, 480, 980):
            ds = stream(n)
            from collections import Counter
            c = Counter(d["category"] for d in ds)
            print(f"  rung ext={n}: " + " ".join(
                f"{k}={c[k]} ({100*c[k]/n:.0f}%)" for k in
                ("sibling", "adjacent", "filler", "variant")))
        # Every supersedes: target is inside the same prefix, AND every
        # retired document has exactly one superseder. The second half is the
        # check that was missing: a template that drops the frontmatter key
        # leaves an orphan archive document and no broken target to trip over.
        for n in (80, 180, 480, 980):
            ds = stream(n)
            have = {d["path"] for d in ds}
            targets = []
            for d in ds:
                for m in re.finditer(r"^supersedes:\s*(\S+)", d["text"], re.M):
                    targets.append(m.group(1))
                    if m.group(1) not in have:
                        print(f"FAIL: {d['path']} supersedes missing {m.group(1)} at n={n}")
                        return 1
            retired = [d["path"] for d in ds if d["category"] == "variant"]
            orphan = sorted(set(retired) - set(targets))
            if orphan:
                print(f"FAIL: {len(orphan)} retired document(s) with no superseder "
                      f"at n={n}: {orphan[:5]}")
                return 1
            if len(targets) != len(set(targets)):
                print(f"FAIL: a supersedes: target is claimed twice at n={n}")
                return 1
        print(f"OK: {len(docs)} documents, no seed entity, prefix-stable, "
              f"supersedes closed at every rung")
        return 0

    if not a.out or not a.count:
        ap.error("--out and --count are required unless --check")
    docs = stream(a.count)
    bad = check_corpus(docs)
    if bad:
        print(f"REFUSING TO WRITE: {len(bad)} seed-entity leaks", file=sys.stderr)
        for b in bad[:20]:
            print("  " + b, file=sys.stderr)
        return 1
    out = Path(a.out)
    for d in docs:
        p = out / d["path"]
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(d["text"], encoding="utf-8")
    # a side file the rung build reads for dates/categories/origins
    meta = out / ".ext-manifest.tsv"
    meta.write_text(
        "".join(f"{d['path']}\t{d['category']}\t{d['origin']}\t{d['date']}\t"
                f"{hashlib.sha256(d['text'].encode()).hexdigest()}\n" for d in docs),
        encoding="utf-8")
    print(f"wrote {len(docs)} documents to {out}")
    return 0


