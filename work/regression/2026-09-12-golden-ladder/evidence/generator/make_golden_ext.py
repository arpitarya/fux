_ENTITY_RE = re.compile(
    "|".join(r"(?<![A-Za-z0-9])" + re.escape(e) + r"(?![A-Za-z0-9])"
             for e in SEED_ENTITIES),
    re.IGNORECASE,
)


def check_corpus(docs: list[dict]) -> list[str]:
    bad = []
    for d in docs:
        for m in _ENTITY_RE.finditer(d["text"]):
            bad.append(f"{d['path']}: seed entity {m.group(0)!r}")
    return bad


