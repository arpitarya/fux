def rng_for(i: int) -> random.Random:
    """Per-document RNG. Depends on the index and nothing else — that is what
    keeps document `i` byte-identical for every `--count`."""
    return random.Random(SEED + i * 7919)


def a_date(r: random.Random, lo: int, hi: int) -> str:
    start = dt.date(lo, 1, 1)
    end = dt.date(hi, 12, 28)
    return (start + dt.timedelta(days=r.randrange((end - start).days))).isoformat()


def pick_company(r: random.Random):
    return r.choice(COMPANIES)


def slug(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


