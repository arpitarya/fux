#!/usr/bin/env python3
"""Build the VS Code extension: one bundled file, then a deterministic `.vsix`.

**Why a script and not `vsce`** (W-286, [SR-VSCODE](../records/0164_vscode.md)).
A `.vsix` is a zip with two XML files beside the extension; the standard
library writes it, so packaging adds no dependency (L2) and the same tree
always zips to the same bytes — every entry carries one fixed timestamp and the
entries are sorted.

**L10: the consumer is served build output.** `vscode/src/` is authored as
CommonJS modules; this script wraps them into ONE `dist/extension.js` with a
generated header naming the version, and only that file ships. Bundled is not
minified — the bundle reads like the source.

    python scripts/build-vsix.py            # -> vscode/dist/fux-<version>.vsix
    python scripts/build-vsix.py --out DIR  # somewhere else

The version is `vscode/package.json`'s, held equal to the engine's by
`scripts/check-version-parity.py`.
"""

from __future__ import annotations

import argparse
import json
import sys
import zipfile
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]
EXT = ROOT / "vscode"
SRC = EXT / "src"
ENTRY = "./extension"
#: 1980-01-01, the earliest time a zip entry can carry — fixed so the bytes are.
EPOCH = (1980, 1, 1, 0, 0, 0)

CONTENT_TYPES = """<?xml version="1.0" encoding="utf-8"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension=".json" ContentType="application/json"/><Default Extension=".js" ContentType="application/javascript"/><Default Extension=".md" ContentType="text/markdown"/><Default Extension=".txt" ContentType="text/plain"/><Default Extension=".vsixmanifest" ContentType="text/xml"/></Types>
"""


def bundle(version: str) -> str:
    """Every module under `vscode/src/`, wrapped into one CommonJS file."""
    parts = [
        f"// fux-vscode {version} — the VS Code extension, bundled. GENERATED by",
        "// scripts/build-vsix.py from vscode/src/; do not edit (L10, SR-VSCODE).",
        '"use strict";',
        "const __modules = {",
    ]
    for path in sorted(SRC.glob("*.js")):
        name = "./" + path.stem
        parts.append(f"{json.dumps(name)}: function (module, exports, require) {{")
        parts.append(path.read_text(encoding="utf-8").rstrip("\n"))
        parts.append("},")
    parts += [
        "};",
        "const __cache = {};",
        "function __require(name) {",
        "  if (!Object.prototype.hasOwnProperty.call(__modules, name)) return require(name);",
        "  if (!__cache[name]) {",
        "    const module = { exports: {} };",
        "    __cache[name] = module;",
        "    __modules[name](module, module.exports, __require);",
        "  }",
        "  return __cache[name].exports;",
        "}",
        f"module.exports = __require({json.dumps(ENTRY)});",
        "",
    ]
    return "\n".join(parts)


def manifest(pkg: dict) -> str:
    tags = ",".join(pkg.get("keywords", []))
    categories = ",".join(pkg.get("categories", []))
    return f"""<?xml version="1.0" encoding="utf-8"?>
<PackageManifest Version="2.0.0" xmlns="http://schemas.microsoft.com/developer/vsx-schema/2011" xmlns:d="http://schemas.microsoft.com/developer/vsx-schema-design/2011">
  <Metadata>
    <Identity Language="en-US" Id="{escape(pkg['name'])}" Version="{escape(pkg['version'])}" Publisher="{escape(pkg['publisher'])}" />
    <DisplayName>{escape(pkg['displayName'])}</DisplayName>
    <Description xml:space="preserve">{escape(pkg['description'])}</Description>
    <Tags>{escape(tags)}</Tags>
    <Categories>{escape(categories)}</Categories>
    <GalleryFlags>Public</GalleryFlags>
    <Properties>
      <Property Id="Microsoft.VisualStudio.Code.Engine" Value="{escape(pkg['engines']['vscode'])}" />
      <Property Id="Microsoft.VisualStudio.Code.ExtensionDependencies" Value="" />
      <Property Id="Microsoft.VisualStudio.Code.ExtensionPack" Value="" />
      <Property Id="Microsoft.VisualStudio.Code.ExtensionKind" Value="workspace" />
      <Property Id="Microsoft.VisualStudio.Code.LocalizedLanguages" Value="" />
      <Property Id="Microsoft.VisualStudio.Services.Links.Source" Value="{escape(pkg['repository']['url'])}" />
      <Property Id="Microsoft.VisualStudio.Services.Links.Getstarted" Value="{escape(pkg['repository']['url'])}" />
      <Property Id="Microsoft.VisualStudio.Services.Links.GitHub" Value="{escape(pkg['repository']['url'])}" />
      <Property Id="Microsoft.VisualStudio.Services.Links.Learn" Value="{escape(pkg['homepage'])}" />
      <Property Id="Microsoft.VisualStudio.Services.GitHubFlavoredMarkdown" Value="true" />
      <Property Id="Microsoft.VisualStudio.Services.Content.Pricing" Value="Free" />
    </Properties>
    <License>extension/LICENSE.txt</License>
  </Metadata>
  <Installation>
    <InstallationTarget Id="Microsoft.VisualStudio.Code" />
  </Installation>
  <Dependencies />
  <Assets>
    <Asset Type="Microsoft.VisualStudio.Code.Manifest" Path="extension/package.json" Addressable="true" />
    <Asset Type="Microsoft.VisualStudio.Services.Content.Details" Path="extension/readme.md" Addressable="true" />
    <Asset Type="Microsoft.VisualStudio.Services.Content.License" Path="extension/LICENSE.txt" Addressable="true" />
  </Assets>
</PackageManifest>
"""


def build(out_dir: Path) -> Path:
    pkg = json.loads((EXT / "package.json").read_text(encoding="utf-8"))
    entries = {
        "[Content_Types].xml": CONTENT_TYPES,
        "extension.vsixmanifest": manifest(pkg),
        "extension/package.json": (EXT / "package.json").read_text(encoding="utf-8"),
        "extension/dist/extension.js": bundle(pkg["version"]),
        "extension/readme.md": (EXT / "README.md").read_text(encoding="utf-8"),
        "extension/LICENSE.txt": (ROOT / "LICENSE").read_text(encoding="utf-8"),
    }
    out_dir.mkdir(parents=True, exist_ok=True)
    # The bundle also lands beside package.json, so the folder runs unpacked
    # (`code --extensionDevelopmentPath=vscode`).
    (EXT / "dist").mkdir(exist_ok=True)
    (EXT / "dist" / "extension.js").write_text(entries["extension/dist/extension.js"], encoding="utf-8")
    target = out_dir / f"{pkg['name']}-{pkg['version']}.vsix"
    with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED) as z:
        for name in sorted(entries):
            info = zipfile.ZipInfo(name, date_time=EPOCH)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            z.writestr(info, entries[name].encode("utf-8"))
    return target


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--out", type=Path, default=EXT / "dist", help="where the .vsix goes")
    args = parser.parse_args()
    print(build(args.out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
